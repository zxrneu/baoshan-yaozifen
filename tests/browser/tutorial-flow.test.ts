/** 新手教学浏览器验收：操作真实入口与题目，验证手机命中、键盘及活动历史隔离。 */
import { test, expect } from '@playwright/test';
import type { HistoryWrite } from '../../src/history/transport';

test('两段教学可完成或退出，原对局暂停且不产生额外历史动作或模型请求', async ({ page }, info) => {
  await page.addInitScript(() => localStorage.setItem('baoshan_debug_mode', 'true'));
  const initialSave = page.waitForResponse(response => response.url().endsWith('/api/history/write') && response.ok());
  await page.goto('/');
  const packet = (await initialSave).request().postDataJSON() as HistoryWrite;
  await expect(page.getByLabel('对局保存状态')).toHaveText('已保存');
  if (!packet.hand?.handId) throw new Error('初始保存缺少副牌身份');
  const detailUrl = `/api/history/hands/${packet.hand.handId}`;
  const original = await (await page.request.get(detailUrl)).json();
  const requests: string[] = [];
  page.on('request', request => { if (/\/api\/(decision|history\/write)$/.test(request.url())) requests.push(request.url()); });
  const entry = page.getByRole('button', { name: '新手教学', exact: true });
  await entry.click();
  const modal = page.getByRole('dialog', { name: '新手教学' });
  const hand = modal.getByRole('group', { name: '题目手牌' });
  await hand.getByRole('button', { name: 'A♠，10分', exact: true }).click();
  await hand.getByRole('button', { name: 'K♣', exact: true }).click();
  await modal.getByRole('button', { name: '确认分牌', exact: true }).click();
  await expect(modal.getByRole('alert')).toBeVisible();
  await hand.getByRole('button', { name: 'K♣', exact: true }).click();
  await hand.getByRole('button', { name: '10♥，10分', exact: true }).click();
  await hand.getByRole('button', { name: '5♦，5分', exact: true }).click();
  await modal.getByRole('button', { name: '确认分牌', exact: true }).click();
  await expect(modal.getByRole('status')).toContainText('25 分');
  await modal.getByRole('button', { name: '下一段', exact: true }).click();
  await expect(modal.getByRole('heading', { level: 2 })).toBeFocused();
  await expect(modal.getByRole('heading', { level: 3 })).toBeInViewport();
  await expect(hand.getByRole('button', { name: /8♣/ })).toBeDisabled();
  await hand.getByRole('button', { name: 'Q♥', exact: true }).click();
  await modal.getByRole('button', { name: '确认出牌', exact: true }).click();
  await expect(modal.getByRole('status')).toContainText('必须跟红桃');
  await expect(modal.getByRole('status')).toBeInViewport({ ratio: 0.9 });
  await page.screenshot({ path: info.outputPath('tutorial-follow.png') });
  const bounds = await modal.boundingBox();
  const viewport = page.viewportSize()!;
  expect(bounds).not.toBeNull();
  expect(bounds!.x).toBeGreaterThanOrEqual(0); expect(bounds!.y).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(viewport.width);
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(viewport.height);
  await modal.getByRole('button', { name: '继续：缺门时', exact: true }).click();
  await expect(hand.getByRole('button', { name: /8♣/ })).toBeEnabled();
  await hand.getByRole('button', { name: '2♦', exact: true }).click();
  await modal.getByRole('button', { name: '确认出牌', exact: true }).click();
  await modal.getByRole('button', { name: '完成教学', exact: true }).click();
  await expect(modal.getByRole('heading', { name: /基础练习完成/ })).toBeVisible();
  await modal.getByRole('button', { name: '返回牌桌', exact: true }).click();
  await expect(entry).toBeFocused();
  await entry.click(); await page.keyboard.press('Escape');
  await expect(modal).toHaveCount(0);
  expect(await (await page.request.get(detailUrl)).json()).toEqual(original);
  expect(requests).toEqual([]);
});
